def _promotable_names() -> list[str]:
    out: list[str] = []
    for name in list_planner_capability_names():
        mat = _node_meta(name)["maturity"].lower()
        if mat in {"experimental", "deprecated", "legacy_alias", "unknown", "prototype"}:
            continue
        out.append(name)
    return out


