def _extract_cap_row(receipt: Mapping[str, Any], name: str) -> dict[str, Any]:
    rows = receipt.get("capabilities")
    if isinstance(rows, list):
        for item in rows:
            if isinstance(item, Mapping) and str(item.get("name") or "") == name:
                return dict(item)
    # alternate shapes
    caps = receipt.get("capability_results")
    if isinstance(caps, Mapping) and name in caps and isinstance(caps[name], Mapping):
        return dict(caps[name])
    return {}


def _consumer_proof(
    name: str,
    *,
    cap_row: Mapping[str, Any],
    receipt: Mapping[str, Any],
    consumer_effect: str,
) -> dict[str, Any]:
    """Observable consumer evidence keyed by consumer_effect."""
    evidence = list(cap_row.get("evidence_refs") or [])
    payload = cap_row.get("consumer_payload") if isinstance(cap_row.get("consumer_payload"), Mapping) else {}
    online = receipt.get("online") if isinstance(receipt.get("online"), Mapping) else {}
    ctx = receipt.get("context_trace") if isinstance(receipt.get("context_trace"), Mapping) else {}
    proof: dict[str, Any] = {
        "consumer_effect": consumer_effect,
        "evidence_refs_present": bool(evidence),
        "local_mode": project_local_execution_mode(name),
    }
    if consumer_effect == "PROMPT_EVIDENCE":
        proof["prompt_marker_or_payload"] = bool(payload) or bool(
            (ctx.get("online_received_context") or {})
        )
        proof["kind"] = "prompt_or_shared_evidence"
    elif consumer_effect == "EXECUTION_CONTROL":
        proof["control_receipt"] = bool(
            cap_row.get("invoked") is True
            and cap_row.get("gate_passed") is True
            and cap_row.get("outcome_contributed") is True
            and str(cap_row.get("semantic_status") or "")
            in {"SUCCEEDED", "VERIFIED"}
            and evidence
        )
        proof["kind"] = "execution_control_receipt"
    elif consumer_effect == "POSTFLIGHT_GATE":
        proof["gate_receipt"] = bool(
            cap_row.get("invoked") is True
            and cap_row.get("gate_passed") is True
            and str(cap_row.get("semantic_status") or "")
            in {"SUCCEEDED", "VERIFIED"}
            and evidence
        )
        proof["kind"] = "postflight_gate_receipt"
    elif consumer_effect == "EXTERNAL_SIDE_EFFECT":
        proof["side_effect_receipt"] = bool(
            str(cap_row.get("status") or "").startswith("BLOCK")
            or cap_row.get("skipped")
            or evidence
        )
        proof["kind"] = "side_effect_or_auth_block_receipt"
    else:
        proof["kind"] = "none"
        proof["control_plane_or_none"] = True
    proof["online_present"] = bool(online)
    return proof


def _local_live_proof_complete(
    *,
    name: str,
    auth_local: bool,
    invoked: bool,
    skipped: bool,
    gate: Any,
    local_stage: Mapping[str, Any],
    local_response: Mapping[str, Any],
    physical_callable: str,
) -> bool:
    """Fail closed on a complete Local model, isolation, hash, verifier receipt."""

    if name not in LOCAL_STAGE_CAPABILITIES or not auth_local:
        return False
    candidate = (
        local_response.get("candidate_summary")
        if isinstance(local_response.get("candidate_summary"), Mapping)
        else {}
    )
    verifier = (
        local_response.get("verifier_summary")
        if isinstance(local_response.get("verifier_summary"), Mapping)
        else {}
    )
    receipt_path = Path(str(local_response.get("receipt_path") or ""))
    try:
        receipt = json.loads(receipt_path.read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError):
        receipt = {}
    return bool(
        invoked
        and not skipped
        and gate is True
        and str(local_stage.get("status") or "").upper()
        in {"SUCCEEDED", "SUCCESS", "VERIFIED", "COMPLETED", "OK", "INVOKED"}
        and not str(local_stage.get("reason") or "").strip()
        and local_response.get("provider") == "ollama"
        and str(local_response.get("physical_callable") or physical_callable)
        == "LocalModelExecutor.run"
        and local_response.get("local_model_invoked") is True
        and local_response.get("output_delivered") is True
        and not str(local_response.get("fallback_reason") or "").strip()
        and candidate.get("isolation_status") == "isolated"
        and candidate.get("selected_candidate_hash_matches_applied") is True
        and bool(candidate.get("selected_candidate_hash"))
        and candidate.get("selected_candidate_hash") == candidate.get("applied_patch_hash")
        and verifier.get("verifier_reached") is True
        and verifier.get("verifier_status") == "pass"
        and receipt.get("receipt_complete") is True
        and receipt.get("terminal_status") == "SUCCEEDED"
        and not str(receipt.get("fallback_reason") or "").strip()
    )


