def _extract_cap_row(receipt: Mapping[str, Any], name: str) -> dict[str, Any]:
    rows = receipt.get("capabilities")
    if isinstance(rows, list):
        for item in rows:
            if isinstance(item, Mapping) and str(item.get("name") or "") == name:
                return dict(item)
    # alternate shapes
    caps = receipt.get("capability_results")
    if isinstance(caps, Mapping) and name in caps and isinstance(caps[name], Mapping):
        return dict(caps[name])
    return {}


def _consumer_proof(
    name: str,
    *,
    cap_row: Mapping[str, Any],
    receipt: Mapping[str, Any],
    consumer_effect: str,
) -> dict[str, Any]:
    """Observable consumer evidence keyed by consumer_effect."""
    evidence = list(cap_row.get("evidence_refs") or [])
    payload = cap_row.get("consumer_payload") if isinstance(cap_row.get("consumer_payload"), Mapping) else {}
    online = receipt.get("online") if isinstance(receipt.get("online"), Mapping) else {}
    ctx = receipt.get("context_trace") if isinstance(receipt.get("context_trace"), Mapping) else {}
    proof: dict[str, Any] = {
        "consumer_effect": consumer_effect,
        "evidence_refs_present": bool(evidence),
        "local_mode": project_local_execution_mode(name),
    }
    if consumer_effect == "PROMPT_EVIDENCE":
        proof["prompt_marker_or_payload"] = bool(payload) or bool(
            (ctx.get("online_received_context") or {})
        )
        proof["kind"] = "prompt_or_shared_evidence"
    elif consumer_effect == "EXECUTION_CONTROL":
        proof["control_receipt"] = bool(
            cap_row.get("invoked") or cap_row.get("physical_callable") or payload
        )
        proof["kind"] = "execution_control_receipt"
    elif consumer_effect == "POSTFLIGHT_GATE":
        proof["gate_receipt"] = "gate_passed" in cap_row or bool(
            cap_row.get("status") in {"SUCCEEDED", "FAILED", "BLOCKED", "SKIPPED"}
        )
        proof["kind"] = "postflight_gate_receipt"
    elif consumer_effect == "EXTERNAL_SIDE_EFFECT":
        proof["side_effect_receipt"] = bool(
            str(cap_row.get("status") or "").startswith("BLOCK")
            or cap_row.get("skipped")
            or evidence
        )
        proof["kind"] = "side_effect_or_auth_block_receipt"
    else:
        proof["kind"] = "none"
        proof["control_plane_or_none"] = True
    proof["online_present"] = bool(online)
    return proof


def _run_family_canary(name: str, *, positive: bool) -> dict[str, Any]:
    contract = PLANNER_EXECUTION_CONTRACTS[name]
    family_ctx = _family_positive_context(name) if positive else {}
    task_id = f"{'pos' if positive else 'neg'}-{name}"
    statement = (
        family_ctx.get("task_statement")
        if positive
        else f"negative canary omit evidence for {name}"
    )
    req = UnifiedRuntimeRequest(
        task_id=task_id,
        workspace_revision="rev-family-canary",
        task_statement=str(statement),
        task_type=str(family_ctx.get("task_type") or "codeintel"),
        route={
            "recommended_flow": "direct",
            "injected_transport": True,
            "online_policy": "auto",
            "mainchain_entry": True,
        },
        online_enabled=True,
        online_prompt="family canary",
        codeintel=dict(family_ctx.get("codeintel") or {})
        if positive
        else {"scan_report_present": False},
    )
    # Merge family context into request via codeintel/evidence only; full
    # constraints ride through capability invokers via planner selection path.
    planner = _SelectPlanner([name], required=[name] if positive else [])
    receipt = run_mainchain(
        req,
        online_invoker=_online_invoker,
        planner=planner,
        verifier=lambda c: {
            "task_id": c["task_id"],
            "invoked": True,
            "gate_passed": bool(positive),
            "verifier_status": "passed" if positive else "failed",
            "verifier_artifact": "artifact-proof-value-long-enough-for-gate"
            if positive
            else "",
            "source_hash": "src_hash_value_long_enough_01" if positive else "",
            "evidence_refs": [f"v:{c['task_id']}"] if positive else [],
        },
        learning=lambda c: {
            "task_id": c["task_id"],
            "invoked": True,
            "gate_passed": True,
            "evidence_refs": [f"l:{c['task_id']}"],
        },
    )
    # Inject family positive fields into capability invoker path by re-invoking
    # selected capability with rich context when positive (mainchain already ran;
    # we also attach planner-selected proof from receipt).
    ctx_trace = receipt.get("context_trace") if isinstance(receipt.get("context_trace"), Mapping) else {}
    selected = [str(x) for x in (ctx_trace.get("selected_capabilities") or [])]
    cap_row = _extract_cap_row(receipt, name)

    # For positive REAL paths that need allowlisted constraints, drive invoker
    # through the same registry map used by mainchain (second probe).
    from nexus.services.capability_registry import build_default_mainchain_invokers

    invokers = build_default_mainchain_invokers(
        codeintel=dict(family_ctx.get("codeintel") or {}) if positive else None
    )
    inv = invokers.get(name)
    inv_out: dict[str, Any] = {}
    if inv is not None:
        inv_ctx: dict[str, Any] = {
            "task_id": task_id,
            "task_statement": str(statement),
            "planner": {
                "plan_hash": f"ph-{name}",
                "selected_capabilities": [name],
                "required_capabilities": [name] if positive else [],
            },
        }
        if positive:
            inv_ctx.update(family_ctx)
        else:
            # Negative: untriggered / missing evidence
            inv_ctx["planner"] = {}
        inv_out = dict(inv(inv_ctx))

    invoked = bool(inv_out.get("invoked") or cap_row.get("invoked"))
    skipped = bool(inv_out.get("skipped") or cap_row.get("skipped"))
    gate = inv_out.get("gate_passed")
    if gate is None:
        gate = cap_row.get("gate_passed")
    status = str(
        inv_out.get("status")
        or (inv_out.get("response") or {}).get("status")
        or cap_row.get("status")
        or ""
    )
    physical = str(
        inv_out.get("physical_callable")
        or cap_row.get("physical_callable")
        or contract.get("physical_callable")
        or ""
    )
    outcome = inv_out.get("response") if isinstance(inv_out.get("response"), Mapping) else {}
    if not outcome and isinstance(inv_out.get("outcome"), Mapping):
        outcome = dict(inv_out["outcome"])
    nested = outcome.get("outcome") if isinstance(outcome.get("outcome"), Mapping) else outcome
    action = str((nested or {}).get("action") or "")
    evidence = list(
        inv_out.get("evidence_refs")
        or cap_row.get("evidence_refs")
        or (nested or {}).get("evidence_refs")
        or []
    )

    ec = str(contract["execution_class"])
    consumer_effect = str(contract["consumer_effect"])
    consumer = _consumer_proof(
        name, cap_row=inv_out or cap_row, receipt=receipt, consumer_effect=consumer_effect
    )

    first_broken: str | None = None
    final_status = "OK"

    if name not in selected and positive:
        first_broken = "not_selected_by_planner"
        final_status = "FAIL"
    if "fixture" in physical.lower() or physical.startswith("test:"):
        first_broken = first_broken or "fixture_callable"
        final_status = "FAIL"
    if action in _SHALLOW_ACTIONS and positive and bool(gate):
        first_broken = first_broken or f"probe_only_success:{action}"
        final_status = "PROBE"

    if positive:
        if ec in REAL_EXECUTION_CLASSES:
            if not invoked and not skipped:
                first_broken = first_broken or "real_not_invoked"
                final_status = "FAIL"
            if status in {"FAILED", "BLOCKED", "BLOCKED_EXECUTOR_UNAVAILABLE"} or gate is False:
                # EXTERNAL_AUTH may legitimately block; REAL must not.
                if ec != EXECUTION_CLASS_EXTERNAL_AUTH_REQUIRED:
                    first_broken = first_broken or f"real_positive_failed:{status or gate}"
                    final_status = "FAIL"
            if not evidence and not skipped:
                first_broken = first_broken or "missing_evidence_refs"
                final_status = "FAIL"
            if not physical:
                first_broken = first_broken or "missing_physical_callable"
                final_status = "FAIL"
        elif ec == EXECUTION_CLASS_EXTERNAL_AUTH_REQUIRED:
            # Fail-closed without auth is acceptable terminal.
            if gate is True and action in _SHALLOW_ACTIONS:
                first_broken = first_broken or "external_auth_probe_success"
                final_status = "FAIL"
        elif ec == EXECUTION_CLASS_CONTROL_PLANE_REFERENCE:
            if bool((nested or {}).get("not_production_executor_f") is False):
                first_broken = first_broken or "control_plane_disguised_as_f"
                final_status = "FAIL"
        elif ec == EXECUTION_CLASS_LEGACY_ALIAS:
            if not (nested or {}).get("legacy_alias_of") and not (nested or {}).get(
                "not_independent_executor"
            ):
                # alias may only skip
                if invoked and not skipped and not (nested or {}).get("legacy_alias_of"):
                    pass
        elif ec == EXECUTION_CLASS_EXPERIMENTAL_NOT_PROMOTED:
            if gate is True and status == "SUCCEEDED" and not (nested or {}).get(
                "experimental_not_promoted"
            ):
                # allow load_registry experimental proof if marked
                pass
    else:
        # Negative: untriggered skip or missing-evidence fail — not false green success.
        if ec in REAL_EXECUTION_CLASSES:
            if gate is True and invoked and status == "SUCCEEDED" and not evidence:
                first_broken = first_broken or "negative_false_green"
                final_status = "FAIL"
            # Accept skip or failed gate as negative success
            if not (skipped or gate is False or status in {"FAILED", "BLOCKED", "SKIPPED"} or not invoked):
                # Some defaults may still run — require no public claim
                if receipt.get("claim_boundary", {}).get("public_claim_allowed") is True:
                    first_broken = first_broken or "negative_public_claim"
                    final_status = "FAIL"

    if contract.get("public_claim_allowed") is not False:
        first_broken = first_broken or "public_claim_allowed_not_false"
        final_status = "FAIL"
    public_claim = receipt.get("claim_boundary") if isinstance(receipt.get("claim_boundary"), Mapping) else {}
    if public_claim.get("public_claim_allowed") is True:
        first_broken = first_broken or "receipt_public_claim_true"
        final_status = "FAIL"

    return {
        "capability": name,
        "positive": positive,
        "execution_class": ec,
        "consumer_effect": consumer_effect,
        "selected": selected,
        "planner_selected": name in selected,
        "invoked": invoked,
        "skipped": skipped,
        "gate_passed": gate,
        "status": status,
        "physical_callable": physical,
        "action": action,
        "evidence_refs": evidence[:8],
        "consumer_proof": consumer,
        "mainchain_entry": True,
        "public_claim_allowed": False,
        "first_broken_edge": first_broken,
        "final_status": final_status,
        "invoker_probe": {
            "pos_invoked" if positive else "neg_invoked": invoked,
            "pos_gate" if positive else "neg_gate": gate,
            "pos_status" if positive else "neg_status": status,
            "skipped": skipped,
        },
    }


def build_and_write_closure_receipt() -> dict[str, Any]:
    """Generate honest closure receipt (SCRATCH + /tmp mirror)."""
    SCRATCH.mkdir(parents=True, exist_ok=True)
    root = Path(__file__).resolve().parents[2]
    catalog = build_capability_catalog(repo_root=root)
    promotable = _promotable_names()
    per_cap: list[dict[str, Any]] = []
    probe_only = 0
    fixture_count = 0
    real_positive_fails = 0

    for name in list_planner_capability_names():
        contract = PLANNER_EXECUTION_CONTRACTS[name]
        pos = _run_family_canary(name, positive=True)
        neg = _run_family_canary(name, positive=False)
        # Merge: fail if either broken for promotable REAL
        first_broken = pos.get("first_broken_edge") or neg.get("first_broken_edge")
        final_status = "OK"
        if pos["final_status"] != "OK":
            final_status = pos["final_status"]
        if neg["final_status"] != "OK" and final_status == "OK":
            final_status = neg["final_status"]
        if pos.get("action") in _SHALLOW_ACTIONS and pos.get("gate_passed"):
            probe_only += 1
        phys = str(pos.get("physical_callable") or "")
        if "fixture" in phys.lower() or phys.startswith("test:"):
            fixture_count += 1
        if (
            name in promotable
            and contract["execution_class"] in REAL_EXECUTION_CLASSES
            and pos["final_status"] != "OK"
        ):
            real_positive_fails += 1
        per_cap.append(
            {
                "capability": name,
                "execution_class": contract["execution_class"],
                "maturity": _node_meta(name)["maturity"],
                "promotable": name in promotable,
                "gap_proxy": contract["execution_class"],
                "local_mode": project_local_execution_mode(name),
                "online_mode": project_local_execution_mode(name),
                "consumer_effect": contract["consumer_effect"],
                "public_claim_allowed": False,
                "positive": {
                    k: pos[k]
                    for k in (
                        "invoked",
                        "skipped",
                        "gate_passed",
                        "status",
                        "physical_callable",
                        "action",
                        "evidence_refs",
                        "consumer_proof",
                        "planner_selected",
                        "mainchain_entry",
                    )
                },
                "negative": {
                    k: neg[k]
                    for k in (
                        "invoked",
                        "skipped",
                        "gate_passed",
                        "status",
                        "action",
                        "evidence_refs",
                        "consumer_proof",
                    )
                },
                "first_broken_edge": first_broken,
                "final_status": final_status,
            }
        )

    ec_counts = Counter(c["execution_class"] for c in PLANNER_EXECUTION_CONTRACTS.values())
    prom_missing = [
        n
        for n in promotable
        if PLANNER_EXECUTION_CONTRACTS[n]["execution_class"] == EXECUTION_CLASS_MISSING_ENGINE
    ]
    blockers = [r for r in per_cap if r["final_status"] != "OK"]
    structural = (
        len(list_planner_capability_names()) == 57
        and len(prom_missing) == 0
        and probe_only == 0
        and fixture_count == 0
        and real_positive_fails == 0
        and all(
            r["final_status"] == "OK"
            for r in per_cap
            if r["promotable"] and r["execution_class"] in REAL_EXECUTION_CLASSES
        )
    )
    auth_ext = os.environ.get("NEXUS_EXTERNAL_RUNTIME_AUTHORIZED", "").strip() == "1"
    auth_local = os.environ.get("NEXUS_LOCAL_MODEL_CALL_ALLOWED", "").strip() == "1"
    live = (
        "AUTHORIZED_CANARY_REQUIRED"
        if (auth_ext or auth_local)
        else "BLOCKED_EXTERNAL_AUTH"
    )

    receipt: dict[str, Any] = {
        "schema": "nexus.all_capability_closure_receipt.v1",
        "baseline_head": "132d0c85b",
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "planner_contract_count": 57,
        "promotable_count": len(promotable),
        "default_real_count": ec_counts.get("DEFAULT_REAL", 0),
        "triggered_real_count": ec_counts.get("TRIGGERED_REAL", 0),
        "stage_owned_real_count": ec_counts.get("STAGE_OWNED_REAL", 0),
        "external_auth_required_count": ec_counts.get("EXTERNAL_AUTH_REQUIRED", 0),
        "control_plane_count": ec_counts.get("CONTROL_PLANE_REFERENCE", 0),
        "experimental_count": ec_counts.get("EXPERIMENTAL_NOT_PROMOTED", 0),
        "alias_count": ec_counts.get("LEGACY_ALIAS", 0),
        "missing_engine_count": ec_counts.get("MISSING_ENGINE", 0),
        "promotable_missing_engine_count": len(prom_missing),
        "probe_only_success_count": probe_only,
        "fixture_callable_count": fixture_count,
        "real_positive_fail_count": real_positive_fails,
        "routing_surface_changed": False,
        "public_claim_allowed": False,
        "catalog_denominators": {
            "union": catalog.get("canonical_union_count"),
            "canonical": catalog.get("canonical_row_count"),
            "alias": catalog.get("alias_row_count"),
            "planner": catalog.get("planner_node_count"),
        },
        "execution_class_counts": dict(ec_counts),
        "local_online_projection": {
            "planner_contract_count": 57,
            "independent_local_truth": False,
            "modes": {
                n: project_local_execution_mode(n) for n in list_planner_capability_names()
            },
        },
        "per_capability": per_cap,
        "blockers": blockers,
        "structural_closure": structural,
        "live_provider_closure": live,
        "live_online_complete": False,
        "live_local_complete": False,
    }
    text = json.dumps(receipt, indent=2, ensure_ascii=False) + "\n"
    RECEIPT_PATH.write_text(text, encoding="utf-8")
    RECEIPT_TMP.write_text(text, encoding="utf-8")
    return receipt


def test_generate_closure_receipt_required() -> None:
    """Receipt generation is mandatory — suite fails closed if generation fails."""
    receipt = build_and_write_closure_receipt()
    assert RECEIPT_PATH.is_file()
    assert RECEIPT_TMP.is_file()
    assert receipt["planner_contract_count"] == 57
    assert receipt["promotable_count"] == 53
    assert receipt["promotable_missing_engine_count"] == 0
    assert receipt["probe_only_success_count"] == 0
    assert receipt["fixture_callable_count"] == 0
    assert receipt["routing_surface_changed"] is False
    assert receipt["public_claim_allowed"] is False
    assert receipt["structural_closure"] is True, receipt.get("blockers", [])[:10]
    # REAL promotable must not remain in blockers
    real_blockers = [
        b
        for b in receipt["blockers"]
        if b.get("promotable") and b.get("execution_class") in REAL_EXECUTION_CLASSES
    ]
    assert real_blockers == [], real_blockers[:8]


@pytest.mark.parametrize("name", _promotable_names())
def test_promotable_family_canary_mainchain_entry(name: str) -> None:
    """Each promotable node: pos+neg via MainchainEntry path, consumer proof, no false green."""
    pos = _run_family_canary(name, positive=True)
    neg = _run_family_canary(name, positive=False)
    contract = PLANNER_EXECUTION_CONTRACTS[name]
    assert pos["mainchain_entry"] is True
    assert pos["planner_selected"] is True
    assert pos["public_claim_allowed"] is False
    assert pos["final_status"] == "OK", (name, pos["first_broken_edge"], pos)
    assert neg["final_status"] == "OK", (name, neg["first_broken_edge"], neg)
    # Consumer proof present for non-NONE effects
    if contract["consumer_effect"] != "NONE":
        assert pos["consumer_proof"].get("kind")
        if contract["consumer_effect"] == "PROMPT_EVIDENCE":
            assert pos["consumer_proof"].get("evidence_refs_present") or pos[
                "consumer_proof"
            ].get("prompt_marker_or_payload")
        if contract["consumer_effect"] == "POSTFLIGHT_GATE":
            assert pos["consumer_proof"].get("gate_receipt")
        if contract["consumer_effect"] == "EXECUTION_CONTROL":
            assert pos["consumer_proof"].get("control_receipt")
    # REAL requires physical invoke + evidence on positive
    if contract["execution_class"] in REAL_EXECUTION_CLASSES:
        assert pos["invoked"] is True or pos["skipped"] is False
        assert pos["physical_callable"]
        assert pos["evidence_refs"] or pos["action"]
        assert pos["action"] not in _SHALLOW_ACTIONS or pos["gate_passed"] is not True
    # EXTERNAL_AUTH: must not probe-success without auth
    if contract["execution_class"] == EXECUTION_CLASS_EXTERNAL_AUTH_REQUIRED:
        if pos["gate_passed"] is True:
            assert pos["action"] not in _SHALLOW_ACTIONS
    # Negative false-green: must not claim success with empty evidence for REAL
    if contract["execution_class"] in REAL_EXECUTION_CLASSES:
        if neg["gate_passed"] is True and neg["invoked"] is True:
            assert neg["status"] != "SUCCEEDED" or neg["evidence_refs"] or neg["skipped"]
